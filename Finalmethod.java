package com.tnsif.encapsulation;
// demo for encapsulation
public class Student {
	
	private int id; //data members
	private String name;
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	
	

}
